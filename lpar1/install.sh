DURATION=7300

# Ensure DOMAIN is set
if [[ -z "$DOMAIN" ]]; then
    echo "OSO Domain not set"
    exit 1
fi
export DOMAIN

#############################################################################################################################
#############################################################################################################################
function createcerts {

    ## CA
    [ -f lpar1-ca-key.pem ] || openssl genrsa -out lpar1-ca-key.pem 4096
    [ -f lpar1-ca.crt ] || {
        openssl req -config ca.cnf -key lpar1-ca-key.pem -new -out lpar1-ca-req.csr
        openssl x509 -signkey lpar1-ca-key.pem -extfile ca.cnf -extensions v3_ca -in lpar1-ca-req.csr -req -days $DURATION -out lpar1-ca.crt
    }

    # Logging server certificate
    [ -f lpar1-logging-server-key.pem ] || openssl genrsa -out lpar1-logging-server-key.pem 4096
    [ -f lpar1-logging-server.crt ] || {
        openssl req -config logging-server.cnf -key lpar1-logging-server-key.pem -new -out lpar1-logging-server-req.csr
        openssl x509 -in lpar1-logging-server-req.csr -req -days $DURATION -CA lpar1-ca.crt -CAkey lpar1-ca-key.pem -CAcreateserial -extfile logging-server.cnf -extensions logging-server -out lpar1-logging-server.crt
    }

    # Client certificate
    [ -f lpar1-client-key.pem ] || openssl genrsa -out lpar1-client-key.pem 4096
    [ -f lpar1-client.crt ] || {
        openssl req -config client.cnf -key lpar1-client-key.pem -new -out lpar1-client-req.csr
        openssl x509 -in lpar1-client-req.csr -req -days $DURATION -CA lpar1-ca.crt -CAkey lpar1-ca-key.pem -CAcreateserial -out lpar1-client.crt
    }
    # Uncomment this line if PKCS8 format is required:
    # openssl pkcs8 -topk8 -inform PEM -outform PEM -nocrypt -in lpar1-client-key.pem -out lpar1-client-key-pkcs8.pem

    # SCP files to remote server
    scp lpar1-logging-server.crt lpar1-client.crt lpar1-client-key.pem root@192.168.0.2:/root/oso-install-main/new-vm-lpar2
}

#############################################################################################################################
#############################################################################################################################
function setrsyslog {

    # Certificates must exist (generated by menu option 1)
    for f in lpar1-ca.crt lpar1-logging-server.crt lpar1-logging-server-key.pem; do
        if [ ! -f "$f" ]; then
            echo "ERROR: Missing certificate file: $f - run option 1 (Generate certificates) first"
            read -p "Press Enter to return to the menu..." _
            return
        fi
    done

    # Check for existing rsyslog config and /logging content; delete only after confirmation
    existing_confs=()
    for v in relp imcp; do
        [ -f "/etc/rsyslog.d/100-server-$v.conf" ] && existing_confs+=("/etc/rsyslog.d/100-server-$v.conf")
    done
    existing_logging=()
    if [ -d /logging ]; then
        while IFS= read -r -d '' f; do existing_logging+=("$f"); done < <(find /logging -mindepth 1 -print0)
    fi
    if [ ${#existing_confs[@]} -gt 0 ] || [ ${#existing_logging[@]} -gt 0 ]; then
        echo "WARNING: Existing rsyslog configuration found:"
        [ ${#existing_confs[@]} -gt 0 ] && printf '  %s\n' "${existing_confs[@]}"
        [ ${#existing_logging[@]} -gt 0 ] && printf '  %s\n' "${existing_logging[@]}"
        read -p "Delete the above config file(s) and empty /logging? (y/Y = delete, anything else = back to menu): " answer
        if [[ "$answer" == "y" || "$answer" == "Y" ]]; then
            [ ${#existing_confs[@]} -gt 0 ] && rm -f "${existing_confs[@]}"
            [ -d /logging ] && find /logging -mindepth 1 -delete
        else
            return
        fi
    fi

    # Select rsyslog variant (relp and imcp configs must not be mixed)
    read -p "rsyslog variant (relp/imcp): " RSYSLOG_VARIANT
    RSYSLOG_VARIANT=${RSYSLOG_VARIANT,,}
    if [[ "$RSYSLOG_VARIANT" != "relp" && "$RSYSLOG_VARIANT" != "imcp" ]]; then
        echo "Invalid rsyslog variant: '$RSYSLOG_VARIANT' (use relp or imcp)"
        return
    fi
    for v in relp imcp; do
        if [ ! -f 100-server-$v.conf ]; then
            echo "Missing 100-server-$v.conf"
            return
        fi
    done

    # Prepare /logging directory
    mkdir -p /logging
    cp lpar1-ca.crt /logging/
    cp lpar1-logging-server.crt /logging/
    cp lpar1-logging-server-key.pem /logging/

    # Open rsyslog listener ports in firewalld (only if not already allowed)
    RSYSLOG_PORTS="6514"
    [ "$RSYSLOG_VARIANT" == "relp" ] && RSYSLOG_PORTS="6514 6517"
    if systemctl is-active --quiet firewalld; then
        fw_changed=0
        for p in $RSYSLOG_PORTS; do
            if ! firewall-cmd --query-port="$p/tcp" >/dev/null 2>&1; then
                echo "firewalld: opening tcp/$p"
                firewall-cmd --permanent --add-port="$p/tcp" && fw_changed=1
            fi
        done
        [ $fw_changed -eq 1 ] && firewall-cmd --reload
    else
        echo "NOTE: firewalld is not running - firewall ports not changed"
    fi

    # Configure rsyslog: both variants as .orig, only the selected one active
    cp 100-server-relp.conf /etc/rsyslog.d/100-server-relp.conf.orig
    cp 100-server-imcp.conf /etc/rsyslog.d/100-server-imcp.conf.orig
    cp 100-server-$RSYSLOG_VARIANT.conf /etc/rsyslog.d/100-server-$RSYSLOG_VARIANT.conf

    # ====== SELINUX (always executed before restart) ======
    semanage fcontext -a -t syslog_conf_t "/logging/(.*)"
    for p in $RSYSLOG_PORTS; do
        if ! semanage port -l | grep -E '^syslog(d|_tls)_port_t +tcp' | grep -qw "$p"; then
            echo "SELinux: allowing tcp/$p for rsyslog"
            semanage port -a -t syslogd_port_t -p tcp "$p" 2>/dev/null || semanage port -m -t syslogd_port_t -p tcp "$p"
        fi
    done
    restorecon -R -v /logging

    # ====== RESTART RSYSLOG ======
    echo "Restarting rsyslog..."
    systemctl restart rsyslog

    # ====== STATUS CHECK ======
    SERVICE_STATUS=$(systemctl is-active rsyslog)

    if [ "$SERVICE_STATUS" == "active" ]; then
        echo "✅ rsyslog service is now running."
    else
        echo "❌ rsyslog service failed to start. Status: $SERVICE_STATUS"
    fi
}

#############################################################################################################################
## Main
#############################################################################################################################

# Ensure docker certs directory exists
[ -d /etc/docker/certs.d/osoregistry ] || mkdir -p /etc/docker/certs.d/osoregistry

# Ensure osoregistry entry in /etc/hosts
grep -q "osoregistry.$DOMAIN" /etc/hosts || echo "192.168.0.2 osoregistry.$DOMAIN osoregistry" >> /etc/hosts

# Main interactive menu
while true; do
    echo
    echo "Choose option:"
    echo "1) Generate certificates"
    echo "2) Configure rsyslog"
    echo "X) Exit"
    echo

    read -p "Enter your choice (1, 2, or X): " choice
    choice=${choice^^}  # convert input to uppercase

    case $choice in
        1)
            createcerts
            ;;
        2)
            setrsyslog
            ;;
        X)
            exit 0
            ;;
        *)
            echo "Invalid choice."
            ;;
    esac
done
