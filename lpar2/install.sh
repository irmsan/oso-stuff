# Define variables
REGISTRY_USER="registryuser"
REGISTRY_PASS="password"
REGISTRY_ADDRESS="192.168.0.2"
DURATION=7300

if [[ -z "$DOMAIN" ]]; then
    echo "OSO Domain not set"
    exit 1
fi
export DOMAIN

