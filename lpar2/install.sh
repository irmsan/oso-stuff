function setrsyslog {

    # Certificates must exist (generated by menu option 1)
    for f in lpar2-ca.crt lpar2-logging-server.crt lpar2-logging-server-key.pem; do
        if [ ! -f "$f" ]; then
            echo "ERROR: Missing certificate file: $f - run option 1 (Generate certificates) first"
            read -p "Press Enter to return to the menu..." _
            return
        fi
    done

    # Check for existing rsyslog config and /logging content; delete only after confirmation
    existing_confs=()
    for v in relp imcp; do
        [ -f "/etc/rsyslog.d/100-server-$v.conf" ] && existing_confs+=("/etc/rsyslog.d/100-server-$v.conf")
    done
    existing_logging=()
    if [ -d /logging ]; then
        while IFS= read -r -d '' f; do existing_logging+=("$f"); done < <(find /logging -mindepth 1 -print0)
    fi
    if [ ${#existing_confs[@]} -gt 0 ] || [ ${#existing_logging[@]} -gt 0 ]; then
        echo "WARNING: Existing rsyslog configuration found:"
        [ ${#existing_confs[@]} -gt 0 ] && printf '  %s\n' "${existing_confs[@]}"
        [ ${#existing_logging[@]} -gt 0 ] && printf '  %s\n' "${existing_logging[@]}"
        read -p "Delete the above config file(s) and empty /logging? (y/Y = delete, anything else = back to menu): " answer
        if [[ "$answer" == "y" || "$answer" == "Y" ]]; then
            [ ${#existing_confs[@]} -gt 0 ] && rm -f "${existing_confs[@]}"
            [ -d /logging ] && find /logging -mindepth 1 -delete
        else
            return
        fi
    fi

    # Select rsyslog variant (relp and imcp configs must not be mixed)
    echo "NOTE: The same rsyslog variant (relp or imcp) must be selected on LPAR1, LPAR2 and LPAR3."
    echo "      This script cannot check the other LPARs - verify it manually."
    read -p "rsyslog variant (relp/imcp): " RSYSLOG_VARIANT
    RSYSLOG_VARIANT=${RSYSLOG_VARIANT,,}
    if [[ "$RSYSLOG_VARIANT" != "relp" && "$RSYSLOG_VARIANT" != "imcp" ]]; then
        echo "Invalid rsyslog variant: '$RSYSLOG_VARIANT' (use relp or imcp)"
        return
    fi
    for v in relp imcp; do
        if [ ! -f 100-server-$v.conf ]; then
            echo "Missing 100-server-$v.conf"
            return
        fi
    done

    # Files received from LPAR1 must exist
    for i in lpar1-logging-server.crt lpar1-client.crt lpar1-client-key.pem; do
        if [ ! -f "$i" ]; then
            echo "ERROR: Missing file from LPAR1: $i"
            read -p "Press Enter to return to the menu..." _
            return
        fi
    done

    mkdir -p /logging
    cp lpar2-ca.crt /logging/
    cp lpar2-logging-server.crt /logging/
    cp lpar2-logging-server-key.pem /logging/

    # Copy lpar1 files with prefix lpar1- (files from lpar1 should stay as is)
    for i in lpar1-logging-server.crt lpar1-client.crt lpar1-client-key.pem; do
        cp $i /logging/
    done

    # Open rsyslog listener ports in firewalld (only if not already allowed)
    RSYSLOG_PORTS="6514"
    [ "$RSYSLOG_VARIANT" == "relp" ] && RSYSLOG_PORTS="6514 6517"
    if systemctl is-active --quiet firewalld; then
        fw_changed=0
        for p in $RSYSLOG_PORTS; do
            if ! firewall-cmd --query-port="$p/tcp" >/dev/null 2>&1; then
                echo "firewalld: opening tcp/$p"
                firewall-cmd --permanent --add-port="$p/tcp" && fw_changed=1
            fi
        done
        [ $fw_changed -eq 1 ] && firewall-cmd --reload
    else
        echo "NOTE: firewalld is not running - firewall ports not changed"
    fi

    # Both variants as .orig, only the selected one active
    cp 100-server-relp.conf /etc/rsyslog.d/100-server-relp.conf.orig
    cp 100-server-imcp.conf /etc/rsyslog.d/100-server-imcp.conf.orig
    cp 100-server-$RSYSLOG_VARIANT.conf /etc/rsyslog.d/100-server-$RSYSLOG_VARIANT.conf

    # ====== SELINUX (always executed before restart) ======
    semanage fcontext -a -t syslog_conf_t "/logging/(.*)"
    for p in $RSYSLOG_PORTS; do
        if ! semanage port -l | grep -E '^syslog(d|_tls)_port_t +tcp' | grep -qw "$p"; then
            echo "SELinux: allowing tcp/$p for rsyslog"
            semanage port -a -t syslogd_port_t -p tcp "$p" 2>/dev/null || semanage port -m -t syslogd_port_t -p tcp "$p"
        fi
    done
    restorecon -R -v /logging

    # ====== RESTART RSYSLOG ======
    echo "Restarting rsyslog..."
    systemctl restart rsyslog

    # ====== STATUS CHECK ======
    SERVICE_STATUS=$(systemctl is-active rsyslog)

    if [ "$SERVICE_STATUS" == "active" ]; then
        echo "✅ rsyslog service is now running."
    else
        echo "❌ rsyslog service failed to start. Status: $SERVICE_STATUS"
    fi
}

